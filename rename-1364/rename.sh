# ---------------------------------------------------------------------------
# Stage files: a file holding part of a partial class keeps its own name when
# the class is renamed, such as PrivateWorldBeliefs.cs or the many
# PrivateWorld*Tests.cs parts of WorldRuntimeTests. Their names follow too.
# ---------------------------------------------------------------------------
stage_files() {
  note "stage files"
  local map=$SCRATCH/files.map path base stem new
  : > "$map"
  while IFS= read -r path; do
    is_protected "$path" && continue
    base=${path##*/}; stem=${base%%.*}
    case "$stem" in
      PrivateWorld*) new="World${stem#PrivateWorld}" ;;
      Viewer*) new="Server${stem#Viewer}" ;;
      Camp*) new="StartingSite${stem#Camp}" ;;
      Playtest*) die "a file is still named $base; give it a name in stage_files" ;;
      *) continue ;;
    esac
    printf '??%s %s\n' "$stem" "$new" >> "$map"
  done < <(git ls-files | grep -E '/(PrivateWorld|Playtest|Viewer|Camp)[^/]*$' || true)
  if [[ -s "$map" ]]; then
    sort -u -o "$map" "$map"
    RENAME_FILES=1 rename_map "$map" files
  else
    note "no prototype file names left"
  fi
  local left
  left=$({ git ls-files | grep -E '/(PrivateWorld|Playtest|Viewer|Camp)[^/]*$' || true; } |
    while read -r path; do is_protected "$path" || echo "$path"; done)
  [[ -z "$left" ]] || die "files still named after the prototype:
$left"
}

