# split_types SOURCE TYPE=DEST...: moves each listed top-level type (with its
# leading comments and attributes) from SOURCE to DEST, in source order. DEST
# "keep" leaves it in SOURCE. Every top-level type must be listed; "TYPE?=DEST"
# marks a type that may already be gone. New files get SOURCE's usings and
# SPLIT_NAMESPACE.
split_types() {
  local source=$1; shift
  require_file "$source"
  SPLIT_NAMESPACE="$SPLIT_NAMESPACE" perl -e '
    use strict; use warnings;
    my ($source, @pairs) = @ARGV;
    my (%dest, %optional);
    for (@pairs) {
      my ($t, $d) = split /=/, $_, 2;
      if ($t =~ s/\?$//) { $optional{$t} = 1; }
      $dest{$t} = $d;
    }
    open my $in, "<", $source or die "cannot read $source\n";
    my @lines = <$in>; close $in;
    my ($ns_index) = grep { $lines[$_] =~ /^namespace [\w.]+;/ } 0..$#lines;
    defined $ns_index or die "$source has no file-scoped namespace\n";
    my @header = @lines[0..$ns_index - 1];
    my @usings = grep { /^using / } @header;
    my $decl = qr/^(?:public |internal |file )?(?:(?:static|sealed|abstract|readonly|partial) )*(?:record struct|record class|record|class|struct|enum|interface) ([A-Za-z_]\w*)/;
    # Block starts: a declaration line plus the column-0 comments/attributes above it.
    my @starts;
    for my $i ($ns_index + 1 .. $#lines) {
      next unless $lines[$i] =~ $decl;
      my $name = $1;
      my $s = $i;
      $s-- while $s - 1 > $ns_index && $lines[$s - 1] =~ m{^(?://|\[)};
      push @starts, [$s, $name];
    }
    @starts or die "$source declares no types\n";
    my (%out, @order, @keep);
    my $preamble = join "", @lines[$ns_index + 1 .. $starts[0][0] - 1];
    $preamble =~ /\S/ and die "$source has code between its namespace and first type\n";
    for my $k (0..$#starts) {
      my ($s, $type) = @{$starts[$k]};
      my $e = $k < $#starts ? $starts[$k + 1][0] - 1 : $#lines;
      my $block = join "", @lines[$s..$e];
      $block =~ s/\s+\z/\n/;
      exists $dest{$type} or die "unexpected type $type in $source: add it to the split map\n";
      my $d = delete $dest{$type};
      if ($d eq "keep") { push @keep, $block; next; }
      push @order, $d unless exists $out{$d};
      push @{$out{$d}}, $block;
    }
    my @missing = grep { !$optional{$_} } sort keys %dest;
    @missing and die "types not found in $source: @missing\n";
    print STDERR "rename.sh: already gone from $source: ", join(", ", sort keys %dest), "\n" if %dest;
    my $ns = $ENV{SPLIT_NAMESPACE};
    for my $d (@order) {
      -e $d and die "target already exists: $d\n";
      open my $o, ">", $d or die "cannot write $d\n";
      print $o @usings, "\n", "namespace $ns;\n\n", join("\n", @{$out{$d}});
      close $o;
    }
    if (@keep) {
      open my $o, ">", $source or die;
      print $o @header, $lines[$ns_index], "\n", join("\n", @keep);
      close $o;
    } else {
      unlink $source;
    }
  ' "$source" "$@"
}

# prune_usings TYPEMAP FILE...: removes using directives a file does not need:
# its own namespace, ClankerWorld.Simulation.* namespaces none of whose types
# it names, and (with PRUNE_SYSTEM=1) common System namespaces whose marker
# types it does not name.
prune_usings() {
  local typemap=$1; shift
  (( $# > 0 )) || return 0
  TYPEMAP="$typemap" perl -0pi -e '
    BEGIN {
      local $/ = "\n";   # -0 reads whole files; the type map is line based
      open my $m, "<", $ENV{TYPEMAP} or die;
      while (<$m>) { chomp; my ($ns, $t) = split / /; $known{$ns} = 1; push @{$types{$ns}}, $t if defined $t; }
      %markers = (
        "System.Globalization" => qr/\b(?:CultureInfo|NumberStyles|UnicodeCategory|CharUnicodeInfo|StringInfo)\b/,
        "System.Runtime.CompilerServices" => qr/\b(?:ConditionalWeakTable|MethodImpl|MethodImplOptions|Unsafe|CallerMemberName|InterpolatedStringHandler)\b/,
        "System.Security.Cryptography" => qr/\b(?:SHA256|SHA512|RandomNumberGenerator|IncrementalHash|HashAlgorithmName|CryptographicOperations)\b/,
        "System.Text" => qr/\b(?:StringBuilder|Encoding|Rune|NormalizationForm)\b/,
        "System.Text.Json" => qr/\b(?:JsonSerializer|JsonDocument|JsonElement|JsonValueKind|Utf8JsonReader|Utf8JsonWriter|JsonSerializerOptions|JsonNamingPolicy|JsonException)\b/,
        "System.Text.Json.Serialization" => qr/\b(?:JsonIgnore|JsonIgnoreCondition|JsonPropertyName|JsonConverter|JsonPolymorphic|JsonDerivedType|JsonStringEnumConverter|JsonInclude|JsonConstructor|JsonRequired)\b/,
        "System.Buffers.Binary" => qr/\bBinaryPrimitives\b/,
        "System.IO.Compression" => qr/\b(?:Brotli\w*|GZip\w*|ZipArchive\w*|CompressionLevel|CompressionMode)\b/,
        "System.Diagnostics.CodeAnalysis" => qr/\b(?:NotNullWhen|MaybeNullWhen|NotNull|DoesNotReturn|MemberNotNull|SuppressMessage)\b/,
      );
    }
    my ($ns) = /^namespace ([\w.]+);/m;
    my ($head, $body) = /\A(.*?^namespace [\w.]+;\n)(.*)\z/ms or next;
    my @keep;
    for my $line (split /(?<=\n)/, $head) {
      if ($line =~ /^using ([\w.]+);\n/) {
        my $u = $1;
        next if defined $ns && $u eq $ns;
        if ($known{$u}) {
          next unless grep { $body =~ /\b\Q$_\E\b/ } @{$types{$u} // []};
        } elsif ($ENV{PRUNE_SYSTEM} && $markers{$u}) {
          next unless $body =~ $markers{$u};
        }
      }
      push @keep, $line;
    }
    my $usings = join("", @keep);
    $usings =~ s/\A\s+//;            # no blank first line when every using went
    $_ = $usings . $body;
  ' "$@"
}

# add_using FILE NAMESPACE: inserts "using NAMESPACE;" in sorted position
# among the file's plain using directives, unless already present.
add_using() {
  USING="$2" perl -0pi -e '
    my $u = $ENV{USING};
    # Never "exit" here: with -i that truncates the file.
    if (!/^using \Q$u\E;$/m) {
      my @lines = split /(?<=\n)/, $_;
      # The file header: leading usings, blank lines and comments.
      my $end = 0;
      $end++ while $end < @lines && $lines[$end] =~ m{^(?:using [^\n]*;|\s*|//[^\n]*|#![^\n]*)\n\z};
      my @plain = grep { $lines[$_] =~ /^using [\w.]+;\n/ } 0..$end - 1;
      if (!@plain) {
        splice @lines, 0, 0, "using $u;\n", "\n";
      } else {
        my $at;
        for my $i (@plain) {
          my ($name) = $lines[$i] =~ /^using ([\w.]+);/;
          next if $name =~ /^System(?:\.|$)/ && $u !~ /^System(?:\.|$)/;
          if (lc($name) gt lc($u)) { $at = $i; last; }
        }
        $at //= $plain[-1] + 1;
        splice @lines, $at, 0, "using $u;\n";
      }
      $_ = join "", @lines;
    }
  ' "$1"
}

# retarget_types FROM_NS FROM_DIR TO_NS FILE...: the types declared in FILE...
# moved from FROM_NS (folder FROM_DIR) to TO_NS. Rewrites qualified names,
# adds "using TO_NS;" where a moved type is named and removes "using FROM_NS;"
# where no remaining type is.
retarget_types() {
  local from_ns=$1 from_dir=$2 to_ns=$3; shift 3
  local moved=() kept=() t file
  mapfile -t moved < <(declared_types "$@")
  (( ${#moved[@]} > 0 )) || die "retarget_types: no moved types"
  mapfile -t kept < <(declared_types $(git ls-files -- "$from_dir/*.cs" | while read -r f; do [[ -f "$f" ]] && echo "$f"; done))

  local alternation from_re
  alternation=$(IFS='|'; echo "${moved[*]}")
  from_re=${from_ns//./\\.}
  rewrite_regex_optional "\\b$from_re\\.($alternation)\\b" "$to_ns.\$1"

  local typemap=$SCRATCH/typemap
  { echo "$from_ns"; for t in "${kept[@]}"; do echo "$from_ns $t"; done; } > "$typemap"
  local cs=() had=() candidates=()
  mapfile -d '' cs < <(eligible_cs_files)
  mapfile -d '' had < <(printf '%s\0' "${cs[@]}" | xargs -0 -r grep -lZ -- "^using $from_re;" || true)
  local own=()
  mapfile -d '' own < <(git ls-files -z -- "$from_dir/*.cs")
  mapfile -d '' candidates < <(printf '%s\0' "${had[@]}" "${own[@]}" |
    xargs -0 -r grep -lZwE -- "$alternation" || true)
  for file in "${candidates[@]}"; do
    [[ -f "$file" ]] && add_using "$file" "$to_ns"
  done
  (( ${#had[@]} == 0 )) || prune_usings "$typemap" "${had[@]}"
  local partial short=${from_ns##*.}
  partial=$(printf '%s\0' "${cs[@]}" | xargs -0 -r grep -nwE -- "$short\\.($alternation)" || true)
  [[ -z "$partial" ]] || die "partially qualified $short references left:
$partial"
  note "moved ${#moved[@]} types from $from_ns to $to_ns; ${#kept[@]} types stay"
}

