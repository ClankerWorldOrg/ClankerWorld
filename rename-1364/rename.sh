#!/usr/bin/env bash
# Issue #1364: replace the names left over from the prototype with names that
# say what each thing is in the finished game.
#
# Run from the root of a clean ClankerWorld checkout of recent main:
#
#   bash rename.sh                      # every stage, in order
#   STAGES="camp playtest" bash rename.sh
#
# Stages (always run in this order):
#   camp          CampObject(s) -> MapObject(s); the starter camp -> the starting site
#   playtest      Playtest/ merges into World/ (folder, namespace, Playtest* types)
#   harness       core map types out of Harness/ into World/Map/
#   instructions  owner instruction and asset-reference contracts out of Harness/
#   map           SeededMap -> WorldMap, SeededMapGenerator -> SmallTemperateMapGenerator
#   society       SocietyFixture -> SocietyRules, SocietyWorldRuntime -> SocietyRuntime
#   inventory     InventoryFixture -> InventoryAuthority
#   world         PrivateWorld* -> World*, private-world -> world, the game-world mode
#   pace          WorldStartPace.DecidedPlaytest and the playtest calendar helpers
#   server        the ClankerWorld.Viewer host project -> ClankerWorld.Server
#   views         Viewer* observation contracts -> *View
#   wording       comments and docs that still describe code by its prototype history
#   files         files still named PrivateWorld*, Viewer* or Camp* (partial-class parts)
#   tests         tests/ClankerWorld.Simulation.Tests -> tests/ClankerWorld.Tests
#   schema        one save-schema bump for the serialized names that changed
#   restore       regenerates packages.lock.json for the renamed projects
#
# It only renames: git mv for folders and files, namespace lines and known
# identifiers (word-boundary rewrites), and the docs, skills and scripts that
# name the old paths. It never touches CHANGELOG.md, changes/, docs/archive/,
# verification records, or measurement and probe evidence records. Serialized
# names follow the rename (owner decision: old alpha saves need not load), so
# the save schemas are bumped once. Hash and seed inputs keep their bytes.
#
# The script is deterministic and fails loudly when something it expects is
# missing or a new name is already taken, so a rerun on a newer main shows
# exactly what moved. Parts that open pull requests may remove first (the
# fixture world, #1738) are skipped with a message when they are gone. It does
# not commit.
set -euo pipefail

die() { echo "rename.sh: error: $*" >&2; exit 1; }
note() { echo "rename.sh: $*" >&2; }

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || die "run inside a git checkout"
cd "$ROOT"
[[ -f ClankerWorld.sln ]] || die "not the ClankerWorld repository root: $ROOT"
# global.json may be blanked locally to build with an older SDK; ignore it.
dirty=$(git status --porcelain -- . ':(exclude)global.json')
[[ -z "$dirty" ]] || die "working tree has changes; start from a clean checkout:
$dirty"

STAGES=${STAGES:-"camp playtest harness instructions map society inventory world pace server views wording files tests schema restore"}
has_stage() { [[ " $STAGES " == *" $1 "* ]]; }

SIM=src/ClankerWorld.Simulation
TESTS=tests/ClankerWorld.Simulation.Tests
SIM_TESTS=$TESTS/Simulation
SERVER=src/ClankerWorld.Viewer
SCRATCH=$(mktemp -d)
# The C# identifier rewriter that leaves strings and comments alone.
CODE_WORDS=$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/cs-code-words.pl
[[ -f "$CODE_WORDS" ]] || die "cs-code-words.pl must sit next to this script"
trap 'rm -rf "$SCRATCH"' EXIT

# ---------------------------------------------------------------------------
# File selection
# ---------------------------------------------------------------------------

# History and evidence that must keep its original wording.
is_protected() {
  case "$1" in
    CHANGELOG.md|changes/*|docs/archive/*) return 0 ;;
    *.cs.txt) return 0 ;;                       # probe sources kept as evidence
    docs/development/*-probe/*) return 0 ;;
    docs/development/*-equivalence/*) return 0 ;;
    docs/development/*-measurements.md) return 0 ;;
    docs/development/verification-*.md) return 0 ;;  # records of one verification run
    */packages.lock.json) return 0 ;;           # regenerated by dotnet restore
  esac
  return 1
}

# Tracked text files that may name code identifiers or paths, NUL separated.
eligible_files() {
  git ls-files -z -- '*.cs' '*.csproj' '*.props' '*.targets' '*.sln' \
    '*.sh' '*.js' '*.mjs' '*.ps1' '*.py' '*.json' '*.yml' '*.yaml' '*.md' \
    '*.tscn' '*.tres' '*.godot' '*.cfg' '*.txt' '*.service' '*.html' '*.css' '*.iss' |
  while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    is_protected "$file" || printf '%s\0' "$file"
  done
}

eligible_cs_files() {
  eligible_files | while IFS= read -r -d '' file; do
    [[ "$file" == *.cs ]] && printf '%s\0' "$file"
  done
}

# Files containing a word (grep -w: [A-Za-z0-9_] boundaries, same as perl \b).
files_with_word() {
  eligible_files | xargs -0 -r grep -lZw -F -- "$1" || true
}

word_used() { [[ -n "$(eligible_files | xargs -0 -r grep -lw -F -- "$1" || true)" ]]; }

# rename_word OLD NEW: exact word-boundary rewrite of an identifier or dotted
# name. Fails if OLD is not found, and if NEW is already used anywhere.
rename_word() {
  local old=$1 new=$2 files=() clash
  mapfile -d '' files < <(files_with_word "$old")
  (( ${#files[@]} > 0 )) || die "expected name '$old' was not found"
  clash=$(eligible_files | xargs -0 -r grep -lw -F -- "$new" || true)
  [[ -z "$clash" ]] || die "new name '$new' is already used in: $clash"
  OLD="$old" NEW="$new" perl -pi -e 's/\b\Q$ENV{OLD}\E\b/$ENV{NEW}/g' "${files[@]}"
  note "renamed $old -> $new in ${#files[@]} files"
}

# merge_word OLD NEW: like rename_word, but NEW may already exist (two
# namespaces becoming one).
merge_word() {
  local old=$1 new=$2 files=()
  mapfile -d '' files < <(files_with_word "$old")
  (( ${#files[@]} > 0 )) || die "expected name '$old' was not found"
  OLD="$old" NEW="$new" perl -pi -e 's/\b\Q$ENV{OLD}\E\b/$ENV{NEW}/g' "${files[@]}"
  note "merged $old into $new in ${#files[@]} files"
}

# rename_map MAPFILE: simultaneous word-boundary rewrite of every "OLD NEW"
# line (blank lines and # comments ignored). Each OLD must occur somewhere
# unless its line starts with "?"; no NEW may occur anywhere before the
# rewrite. With RENAME_FILES=1, tracked files whose names contain an OLD word
# are moved with git mv to the rewritten name.
rename_map() {
  local map=$1 label=${2:-$(basename "$1")}
  eligible_files > "$SCRATCH/files"
  MAP="$map" LABEL="$label" RENAME_FILES="${RENAME_FILES:-}" perl -e '
    use strict; use warnings;
    my (%map, %optional, @order, %member);
    open my $m, "<", $ENV{MAP} or die "cannot read $ENV{MAP}\n";
    while (<$m>) {
      chomp; s/#.*//; next unless /\S/;
      my $optional = s/^\s*(\?+)\s*// ? length($1) : 0;
      my @f = split " ";
      die "bad map line in $ENV{LABEL}: $_\n" if @f != 2;
      my ($old, $new) = @f;
      # "NEW!" may already occur, as a member name of another type.
      $member{$new} = 1 if $new =~ s/!$//;
      die "duplicate map entry in $ENV{LABEL}: $old\n" if exists $map{$old};
      $map{$old} = $new; $optional{$old} = $optional if $optional; push @order, $old;
    }
    my @olds = sort { length($b) <=> length($a) || $a cmp $b } keys %map;
    my $alt = join "|", map { quotemeta } @olds;
    my $re = qr/(?<![\w])($alt)(?![\w])/;
    my %isold = map { $_ => 1 } @olds;
    my @news = grep { !$isold{$_} && !$member{$_} } sort { length($b) <=> length($a) || $a cmp $b } values %map;
    my %seen; @news = grep { !$seen{$_}++ } @news;
    my $newre = @news ? do { my $n = join "|", map { quotemeta } @news; qr/(?<![\w])($n)(?![\w])/ } : undef;
    local $/ = "\0";
    open my $list, "<", "'"$SCRATCH"'/files" or die;
    my @files = map { chomp; $_ } <$list>;
    close $list;
    local $/;
    my (%count, %clash, %content);
    for my $file (@files) {
      open my $in, "<", $file or die "cannot read $file\n";
      my $text = <$in>; close $in;
      $text = "" unless defined $text;
      if ($newre) { while ($text =~ /$newre/g) { push @{$clash{$1}}, $file; } }
      my $hits = 0;
      while ($text =~ /$re/g) { $count{$1}++; $hits++; }
      $content{$file} = $text if $hits;
    }
    my @missing = grep { !$count{$_} && !$optional{$_} } @order;
    die "$ENV{LABEL}: expected names not found: @missing\n" if @missing;
    if (%clash) {
      my @lines = map { my %f = map { $_ => 1 } @{$clash{$_}}; "  $_ in " . join(", ", sort keys %f) } sort keys %clash;
      die "$ENV{LABEL}: new names already used:\n" . join("\n", @lines) . "\n";
    }
    for my $file (sort keys %content) {
      my $text = $content{$file};
      $text =~ s/$re/$map{$1}/g;
      open my $out, ">", $file or die "cannot write $file\n";
      print $out $text; close $out;
    }
    for my $old (grep { ($optional{$_} // 0) == 1 && !$count{$_} } @order) {
      print STDERR "rename.sh: $ENV{LABEL}: $old is gone; skipped\n";
    }
    printf STDERR "rename.sh: %s: %d names in %d files\n", $ENV{LABEL}, scalar(grep { $count{$_} } @order), scalar(keys %content);
    if ($ENV{RENAME_FILES}) {
      open my $all, "-|", "git", "ls-files", "-z" or die;
      local $/ = "\0";
      my @tracked = map { chomp; $_ } <$all>;
      close $all;
      for my $path (@tracked) {
        next if $path =~ m{^(?:CHANGELOG\.md|changes/|docs/archive/|docs/development/verification-)} || $path =~ /\.cs\.txt$/ ||
          $path =~ m{^docs/development/[^/]*-(?:probe|equivalence)/};
        my ($dir, $base) = $path =~ m{^(.*/)?([^/]+)$};
        $dir //= "";
        (my $renamed = $base) =~ s/$re/$map{$1}/g;
        next if $renamed eq $base;
        my $target = "$dir$renamed";
        die "target already exists: $target\n" if -e $target;
        system("git", "mv", $path, $target) == 0 or die "git mv $path failed\n";
        print STDERR "rename.sh: moved $path -> $target\n";
      }
    }
  '
}

# rewrite_regex PERL_REGEX REPLACEMENT: scoped rewrite over eligible files
# that must change at least one file. REPLACEMENT may use $1 and $2.
rewrite_regex() {
  local pattern=$1 replacement=$2 files=()
  mapfile -d '' files < <(eligible_files | xargs -0 -r grep -lZP -- "$pattern" || true)
  (( ${#files[@]} > 0 )) || die "expected text /$pattern/ was not found"
  PAT="$pattern" REP="$replacement" perl -pi -e '
    BEGIN { $pat = qr/$ENV{PAT}/; $rep = $ENV{REP}; }
    s{$pat}{ my @m = ($1, $2); my $r = $rep; $r =~ s/\$(\d)/defined $m[$1 - 1] ? $m[$1 - 1] : ""/ge; $r }ge;
  ' "${files[@]}"
  note "rewrote /$pattern/ in ${#files[@]} files"
}

# rewrite_regex_optional: the same, but finding nothing is only reported.
rewrite_regex_optional() {
  if eligible_files | xargs -0 -r grep -qP -- "$1"; then rewrite_regex "$@"; else note "skipped /$1/: not found"; fi
}

# replace_in FILE OLD NEW: literal rewrite in one file that must match.
replace_in() {
  local file=$1
  [[ -f "$file" ]] || die "expected file is missing: $file"
  OLD="$2" NEW="$3" perl -0pi -e '$n += s/\Q$ENV{OLD}\E/$ENV{NEW}/g; END { exit($n ? 0 : 3) }' "$file" ||
    die "expected text not found in $file: $2"
}

# replace_in_optional FILE OLD NEW: the same, skipped with a note when absent.
replace_in_optional() {
  if [[ -f "$1" ]] && OLD="$2" perl -0777 -ne 'exit(index($_, $ENV{OLD}) >= 0 ? 0 : 1)' "$1"; then
    replace_in "$@"
  else
    note "skipped in $1: '$2' not found"
  fi
}

require_file() { [[ -f "$1" ]] || die "expected file is missing: $1"; }
require_dir() { [[ -d "$1" ]] || die "expected folder is missing: $1"; }
require_absent() { [[ ! -e "$1" ]] || die "target already exists: $1"; }

move_path() {
  local from=$1 to=$2
  [[ -e "$from" ]] || die "expected path is missing: $from"
  require_absent "$to"
  mkdir -p "$(dirname "$to")"
  git mv "$from" "$to"
  note "moved $from -> $to"
}

# merge_dir FROM TO: moves every tracked entry of FROM into TO, merging
# folders that exist on both sides. Fails if any file would be replaced.
merge_dir() {
  local from=$1 to=$2 entry name
  require_dir "$from"
  mkdir -p "$to"
  for entry in "$from"/* "$from"/.[!.]*; do
    [[ -e "$entry" ]] || continue
    name=${entry##*/}
    [[ -n "$(git ls-files -- "$entry" | head -n 1)" ]] || continue
    if [[ -d "$entry" && -d "$to/$name" ]]; then
      merge_dir "$entry" "$to/$name"
    else
      require_absent "$to/$name"
      git mv "$entry" "$to/$name"
    fi
  done
  rmdir "$from" 2>/dev/null || true
}

# code_words_in "OLD NEW [OLD NEW...]" FILE...: renames code identifiers (not
# strings or comments) in these files only. Each file must name OLD, and no
# file may already name NEW.
code_words_in() {
  local pairs=$1 file old new; shift
  printf '%s\n' $pairs | paste -d ' ' - - > "$SCRATCH/code-words.map"
  for file in "$@"; do
    require_file "$file"
    while read -r old new; do
      [[ -n "$(perl "$CODE_WORDS" list "(?-i)^$old\$" "$file")" ]] || die "$file does not name '$old'"
      [[ -z "$(perl "$CODE_WORDS" list "(?-i)^$new\$" "$file")" ]] || die "$file already names '$new'"
    done < "$SCRATCH/code-words.map"
  done
  perl "$CODE_WORDS" rewrite "$SCRATCH/code-words.map" "$@"
  note "renamed code names ($pairs) in $# files"
}

# Top-level type names declared in C# files (column-0 declarations).
declared_types() {
  (( $# > 0 )) || return 0
  perl -ne 'print "$1\n" if /^(?:public |internal |file )?(?:(?:static|sealed|abstract|readonly|partial|ref|unsafe) )*(?:record struct|record class|record|class|struct|enum|interface) ([A-Za-z_][A-Za-z0-9_]*)/' "$@" | sort -u
}

# dedupe_usings FILE...: drops a repeated plain using directive, and a using
# of the file's own namespace.
dedupe_usings() {
  (( $# > 0 )) || return 0
  perl -0pi -e '
    my ($ns) = /^namespace ([\w.]+);/m;
    my %seen;
    my @lines = split /(?<=\n)/, $_;
    my @kept;
    for my $line (@lines) {
      if ($line =~ /^using ([\w.]+);\n\z/) {
        next if $seen{$1}++;
        next if defined $ns && $1 eq $ns;
      }
      push @kept, $line;
    }
    $_ = join "", @kept;
    s/\A\n+//;
  ' "$@"
}

