# ---------------------------------------------------------------------------
# Stage schema: one save-schema bump. Serialized names changed:
#   world checkpoint     map.campObjects -> map.mapObjects, the file header
#                        clankerworld.private-world-runtime -> clankerworld.world-runtime,
#                        and the save file private-world.json -> world.json
#   owner-world file     Map.CampObjects -> Map.MapObjects
# Older alpha saves are refused by schema, or not found under the new name.
# ---------------------------------------------------------------------------
stage_schema() {
  note "stage schema"
  local runtime old new doc=docs/development/saves-and-replay.md type
  runtime=$(git ls-files -- "$SIM/*/WorldRuntime.cs" "$SIM/*/PrivateWorldRuntime.cs" | head -n 1)
  require_file "$runtime"
  type=$(basename "$runtime" .cs)
  old=$(perl -ne 'print $1 if /public const int StateSchemaVersion = (\d+);/' "$runtime")
  [[ "$old" =~ ^[0-9]+$ ]] || die "$type.StateSchemaVersion not found in $runtime"
  new=$((old + 1))
  require_file "$doc"
  grep -q "^| Schema $new[ |]" "$doc" && die "$doc already has a Schema $new row; rebase this rename onto it"
  grep -qF "\`$type.StateSchemaVersion\` $old." "$doc" || die "$doc does not name $type.StateSchemaVersion $old"

  # The fixture world's own state file had a schema too; #1738 removed it.
  local owner owner_note=""
  owner=$(git ls-files -- "$SIM/*/OwnerWorldRuntime.cs" | head -n 1)
  if [[ -n "$owner" ]] && grep -q 'public const int StateSchemaVersion' "$owner"; then
    grep -q 'public const int StateSchemaVersion = 1;' "$owner" ||
      die "OwnerWorldRuntime.StateSchemaVersion is no longer 1; update stage_schema"
    replace_in "$owner" 'public const int StateSchemaVersion = 1;' 'public const int StateSchemaVersion = 2;'
    owner_note=$'The owner-world state file moves to its\nschema 2 for the same `MapObjects` rename. '
    note "owner-world schema 1 -> 2"
  else
    note "the fixture world's OwnerWorldRuntime is gone; no owner-world schema to bump"
  fi

  replace_in "$runtime" "public const int StateSchemaVersion = $old;" "public const int StateSchemaVersion = $new;"
  replace_in "$doc" "\`$type.StateSchemaVersion\` $old." "\`$type.StateSchemaVersion\` $new."
  # The history row goes after the newest row the table has, which need not
  # be the current schema: a version may be recorded only in prose.
  SCHEMA_OLD=$old SCHEMA_NEW=$new OWNER_NOTE="$owner_note" perl -0pi -e '
    my ($o, $n) = ($ENV{SCHEMA_OLD}, $ENV{SCHEMA_NEW});
    my $row = "| Schema $n | Prototype names leave the save: map objects are saved as `mapObjects` instead of `campObjects`, the checkpoint header is `clankerworld.world-runtime/v2` and the file is `world.json` instead of `private-world.json`. Earlier alpha checkpoints are refused by schema and preserved without migration. This version is provisional until merge. |\n";
    my ($best, $at) = (-1, -1);
    while (/^\| Schema (\d+)[^\n]*\n/mg) { if ($1 <= $o && $1 > $best) { ($best, $at) = ($1, pos); } }
    $at >= 0 or die "no schema history row at or below $o\n";
    substr($_, $at, 0) = $row;
    my $para = "Schema $n removes prototype names from the save\n([#1364](https://github.com/compoodment/ClankerWorld/issues/1364)): map objects are\nsaved as `mapObjects` instead of `campObjects`, the checkpoint header is\n`clankerworld.world-runtime/v2`, and the active save is `saves/world.json`\ninstead of `saves/private-world.json`. $ENV{OWNER_NOTE}A save under the old file name is\nnot found, so the game starts without it and leaves it on disk. An older\ncheckpoint opened by path is refused by schema with the usual reason and left\nunchanged; there is no migration. The version is provisional until merge.\n\n";
    s/^(## Current formats and older worlds\n\n)/$1$para/m or die "no current formats heading\n";
  ' "$doc"

  # Older saves stop loading, which players see, so it gets a changelog entry.
  local entry=changes/1364-prototype-names.md
  require_absent "$entry"
  printf '%s\n' "- The save format and save file name changed during a code cleanup, so the game no longer finds or opens saves from earlier builds and starts as if there were none. Older saves stay on disk; nothing is deleted. A world server on another machine needs a fresh install with this build, and its devices need pairing again." > "$entry"
  git add "$entry"

  # Owner decision: a remote server gets a fresh install of this build, with
  # no compatibility for the old service or its settings.
  local deployment=docs/development/remote-server-deployment.md
  require_file "$deployment"
  grep -q '^## Installing this build on a remote server$' "$deployment" && die "$deployment already has the install section"
  cat >> "$deployment" <<'EOF'

## Installing this build on a remote server

Builds from [#1364](https://github.com/compoodment/ClankerWorld/issues/1364) on
rename the host, its service and its files, and keep nothing from the earlier
service. Install them fresh rather than updating the old service:

1. Stop and disable the old service:
   `sudo systemctl disable --now clankerworld-viewer.service`.
2. Install the new host files and the new
   [systemd template](../../deploy/clankerworld-server.service) from `deploy/`
   as `/etc/systemd/system/clankerworld-server.service`, then run
   `sudo systemctl daemon-reload`.
3. Start it: `sudo systemctl enable --now clankerworld-server.service`.
4. Pair each device again and add the API keys again in the game. Worlds saved
   by earlier builds do not open in this build, so the server starts a new one.
5. Optionally, delete the old `/var/lib/clankerworld-viewer` folder once the new
   server works.
EOF
  note "added the fresh-install section to $deployment"
  note "world schema $old -> $new"
}

