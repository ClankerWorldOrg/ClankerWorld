# ---------------------------------------------------------------------------
# Stage playtest: the game runtime lives in Playtest/. It is the world, so it
# merges into World/ and the ClankerWorld.Simulation.World namespace.
# ---------------------------------------------------------------------------
stage_playtest() {
  note "stage playtest"
  require_dir "$SIM/Playtest"
  require_dir "$SIM_TESTS/Playtest"
  local stray
  stray=$(git grep -L '^namespace ClankerWorld.Simulation.Playtest;' -- "$SIM/Playtest/*.cs" || true)
  [[ -z "$stray" ]] || die "files in $SIM/Playtest use another namespace: $stray"
  git grep -q '^namespace ClankerWorld\.Simulation\.Playtest\.' -- '*.cs' &&
    die "a sub-namespace of ClankerWorld.Simulation.Playtest exists; extend stage_playtest"

  # The two folders and namespaces must not declare the same type.
  local clash
  clash=$(comm -12 <(declared_types $(git ls-files -- "$SIM/Playtest/*.cs")) \
    <(declared_types $(git ls-files -- "$SIM/World/*.cs" "$SIM/Harness/*.cs")) || true)
  [[ -z "$clash" ]] || die "Playtest and World (or the map types bound for it) declare the same types: $clash"

  merge_dir "$SIM/Playtest" "$SIM/World"
  merge_dir "$SIM_TESTS/Playtest" "$SIM_TESTS/World"
  note "merged $SIM/Playtest into $SIM/World, and its tests"

  merge_word ClankerWorld.Simulation.Playtest ClankerWorld.Simulation.World
  local cs=()
  mapfile -d '' cs < <(eligible_cs_files | xargs -0 -r grep -lZ -- '^using ClankerWorld\.Simulation\.World;' || true)
  dedupe_usings "${cs[@]}"
  # Paths in scripts, CI label rules, architecture lists, tests and docs.
  rewrite_regex 'ClankerWorld\.Simulation/Playtest\b' 'ClankerWorld.Simulation/World'
  rewrite_regex_optional '(?<=Simulation/)Playtest/' 'World/'
  replace_in docs/development/how-it-works.md '`Playtest/Goods/`' '`World/Goods/`'
  local left
  left=$(eligible_files | xargs -0 -r grep -nP '(?<![a-z])Playtest/[A-Z]' || true)
  [[ -z "$left" ]] || die "unhandled Playtest/ path left:
$left"

  # Runtime types named after the playtest prototype.
  cat > "$SCRATCH/playtest.map" <<'EOF'
PlaytestInhabitantState InhabitantState
PlaytestDeceasedInhabitantState DeceasedInhabitantState
PlaytestWorldEvent WorldEventEntry           # one entry of WorldEventLog; the client protocol has its own WorldEvent
PlaytestModelAttempt ModelAttempt
PlaytestPrivateThought RecentThought!        # one of RecentThoughts, shown as PrivateThoughtView
PlaytestResourceState ResourceStateEntry     # one saved (resource, state) pair
PlaytestPlannedRoute PlannedRoute!          # as PlannedRouteView and the client's OwnerWorldPlannedRoute
ToPlaytestInhabitant ToInhabitantView
DeterminePlaytestRoute DetermineWorldRoute   # as against DetermineFixtureRoute
EOF
  rename_map "$SCRATCH/playtest.map" playtest
}

